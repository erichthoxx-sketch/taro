const blank = () => ({ up: '', rev: '', general: '', love: '', work: '', health: '', person: '', advice: '', yesno: '', timing: '', astro: '', notes: '', obs: [] });

function tarot78(kind) {
  const cards = [];
  const suits = SUITS[kind], courts = COURTS[kind];
  MAJOR.forEach(([name, up, rev, general, astro], i) => {
    let nm = name;
    if (kind === 'thoth') nm = THOTH_MAJOR[i] || name;
    if (kind === 'marseille') nm = i === 8 ? 'Справедливость' : i === 11 ? 'Сила' : i === 1 ? 'Маг (Фокусник)' : i === 2 ? 'Папесса' : i === 5 ? 'Папа' : i === 13 ? 'Безымянный аркан (Смерть)' : i === 10 ? 'Колесо Фортуны' : name;
    // в Тоте и Марселе VIII и XI поменяны местами относительно Уэйта: значения переносим вместе с названием
    const src = (kind === 'thoth' || kind === 'marseille') && (i === 8 || i === 11) ? MAJOR[i === 8 ? 11 : 8] : [name, up, rev, general, astro];
    cards.push({ ...blank(), key: 'm' + i, order: i, name: nm, group: 'major', numeral: ROMAN[i],
      up: src[1], rev: kind === 'thoth' ? '' : src[2], general: src[3], astro: src[4].replace(/\d+$/, String(i)) });
  });
  SUIT_ORDER.forEach((s, si) => {
    for (let r = 0; r < 14; r++) {
      const court = r >= 10;
      const name = court ? `${courts[r - 10]} ${suits[s][1]}` : `${RANKS[r]} ${suits[s][1]}`;
      const c = { ...blank(), key: s + r, order: 22 + si * 14 + r, name, group: s, numeral: court ? courts[r - 10] : PIP_NUM[r], astro: 'Стихия: ' + ELEMENT[s] };
      if (kind === 'thoth') {
        if (court) { const [, t] = THOTH_COURT[r - 10]; c.up = t; c.general = `Придворная карта масти ${suits[s][0]} (${ELEMENT[s]}): ${t}. Сфера масти: ${SPHERE[s]}.`; }
        else { const [title, t] = THOTH_TITLES[s][r]; c.name = r === 0 ? `Туз ${suits[s][1]}` : `${name} «${title}»`; c.up = `${title}: ${t}`; c.general = `${RANK_NOTE[r]} в сфере масти ${suits[s][0]} (${ELEMENT[s]}): ${SPHERE[s]}.`; }
      } else {
        const [up, rev] = MINOR[s][r];
        c.up = up; c.rev = rev;
        c.general = `${RANK_NOTE[r]} в сфере масти ${suits[s][0]} (${ELEMENT[s]}): ${SPHERE[s]}.` + (kind === 'marseille' && !court && r > 0 ? ' В марсельской колоде числовые карты без сюжетных сцен: значение читают по числу и масти.' : '');
      }
      cards.push(c);
    }
  });
  return cards;
}

// Названия групп для фильтров
export function groupsOf(kind) {
  if (kind === 'lenormand' || kind === 'oracle') return [];
  const suits = SUITS[kind] || SUITS.rws;
  return [['major', 'Старшие арканы'], ...SUIT_ORDER.map((s) => [s, suits[s][0]])];
}

// names — для оракула: список названий (по строке на карту); count — сколько карт, если названий нет
export function templateCards(kind, { names = [], count = 0 } = {}) {
  if (kind === 'rws' || kind === 'thoth' || kind === 'marseille') return tarot78(kind);
  if (kind === 'lenormand') return LENORMAND.map(([name, up, play], i) => ({ ...blank(), key: 'l' + (i + 1), order: i, name, group: 'lenormand', numeral: String(i + 1), up, astro: 'Игральная карта: ' + play }));
  const list = names.length ? names : Array.from({ length: count }, (_, i) => `Карта ${i + 1}`);
  return list.map((name, i) => ({ ...blank(), key: 'o' + (i + 1), order: i, name, group: 'oracle', numeral: String(i + 1) }));
}

